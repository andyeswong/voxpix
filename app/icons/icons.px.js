const frame = (face, hi, lo, edge) => (c) => {
  c.rect(0, 0, 12, 12, edge)
  c.rect(1, 1, 10, 10, face)
  c.hline(1, 1, 10, hi); c.vline(1, 1, 10, hi)
  c.hline(1, 10, 10, lo); c.vline(10, 1, 10, lo)
  c.px(0, 0, "_"); c.px(11, 0, "_"); c.px(0, 11, "_"); c.px(11, 11, "_")
}
