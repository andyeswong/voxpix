import { writeFileSync } from 'node:fs';
import { generateLayout } from '../src/worldgen';
import { THEMES } from '../src/content/themes';
import { buildWorld } from '../src/world/build';
import { bakeWorld, lightView } from '../src/world/bake';
import { buildLayers, applyLayers } from '../src/lighting/shade';
import { encodePNG } from '../src/core/png';
const theme = (process.argv[2] ?? 'medieval') as 'medieval';
const t0 = performance.now();
const layout = generateLayout(THEMES[theme].spec, Number(process.argv[3] ?? 7));
const world = buildWorld(layout, theme);
const t1 = performance.now();
const b = bakeWorld(world);
console.log(theme, 'voxels', world.model.size, 'build ms', Math.round(t1 - t0), 'bake', b.ms, 'img', b.width, b.height, 'lights', b.lights.length);
const a = THEMES[theme].ambient;
const t2 = performance.now();
const total = lightView(b, 0, 0, b.width, b.height, a, 0);
const layers = buildLayers({ cell: 1, cols: b.width, rows: b.height, ambient: a, total }, { x: 0, y: 0, width: b.width, height: b.height }, { steps: 8, softGlow: true });
const lit = applyLayers(b.rgba, layers);
console.log('frame (full image) ms', Math.round(performance.now() - t2));
writeFileSync(`out/mundo_${theme}.png`, encodePNG(b.width, b.height, lit, 2));
writeFileSync(`out/mundo_${theme}_plano.png`, encodePNG(b.width, b.height, b.rgba, 1));
